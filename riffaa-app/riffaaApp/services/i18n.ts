const i18n = new I18n(translations);
i18n.enableFallback = true;
i18n.defaultLocale = 'ar';

const supportedLocales = ['ar', 'en', 'fr'] as const;

function resolveLocale(): (typeof supportedLocales)[number] {
  const device = Localization.getLocales()[0]?.languageCode ?? 'ar';
  return (supportedLocales as readonly string[]).includes(device)
    ? (device as (typeof supportedLocales)[number])
    : 'ar';
}

i18n.locale = resolveLocale();

export function translate(key: string, config?: TranslateOptions) {
  return i18n.t(key, config);
}

export function setLocale(locale: string) {
  i18n.locale = locale;
}

export function currentLocale() {
  return i18n.locale;
}

